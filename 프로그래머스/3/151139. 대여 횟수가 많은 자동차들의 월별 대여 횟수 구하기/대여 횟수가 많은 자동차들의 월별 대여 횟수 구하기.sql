SELECT Month(C1.START_DATE), C1.CAR_ID, COUNT(*) AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY C1
Inner Join (
    SELECT CAR_ID 
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE START_DATE >='2022-08-01' AND START_DATE <'2022-11-01'
    GROUP BY CAR_ID
    HAVING COUNT(CAR_ID) >=5
) AS C2 ON C1.CAR_ID = C2.CAR_ID
WHERE C1.START_DATE >='2022-08-01' AND C1.START_DATE <'2022-11-01'
GROUP BY C1.CAR_ID, MONTH(C1.START_DATE)
ORDER BY MONTH(START_DATE) ASC, C1.CAR_ID DESC