SELECT FD2.CATEGORY, FD2.MAX_PRICE, FD1.PRODUCT_NAME
FROM FOOD_PRODUCT FD1
Inner JOIN (
SELECT CATEGORY, MAX(PRICE) as MAX_PRICE
FROM FOOD_PRODUCT 
WHERE CATEGORY IN ('과자', '국', '김치', '식용유')
GROUP BY CATEGORY
) as FD2 ON FD2.CATEGORY = FD1.CATEGORY AND FD2.MAX_PRICE = FD1.PRICE
ORDER BY MAX_PRICE DESC

