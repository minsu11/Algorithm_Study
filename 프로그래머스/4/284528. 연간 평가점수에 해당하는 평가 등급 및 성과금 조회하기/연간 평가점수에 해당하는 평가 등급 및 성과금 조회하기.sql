SELECT HE.EMP_NO, HE.EMP_NAME AS EMP_NAME, 
CASE 
    WHEN SUM(HG.SCORE) / 2 >= 96 THEN 'S'
    WHEN SUM(HG.SCORE) / 2 >= 90 THEN 'A'
    WHEN SUM(HG.SCORE) / 2 >= 80 THEN 'B'
    ELSE 'C'
END AS GRADE,
CASE 
    WHEN SUM(HG.SCORE) / 2 >=96 THEN HE.SAL * 0.2
    WHEN SUM(HG.SCORE) / 2 >= 90 THEN HE.SAL * 0.15
    WHEN SUM(HG.SCORE) / 2 >= 80 THEN HE.SAL * 0.1
    ELSE 0
END AS BONUS
FROM HR_EMPLOYEES HE
INNER JOIN HR_DEPARTMENT HD ON HD.DEPT_ID = HE.DEPT_ID
INNER JOIN HR_GRADE HG ON HG.EMP_NO = HE.EMP_NO
GROUP BY HE.EMP_NO
ORDER BY HE.EMP_NO
